CREATE TABLE APPUSER.ROLES (
    ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE      VARCHAR2(50)  NOT NULL,
    DESCRIPCION VARCHAR2(200),
    CONSTRAINT PK_ROLES PRIMARY KEY (ID),
    CONSTRAINT UK_ROLES_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE APPUSER.USUARIOS (
    ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE   VARCHAR2(100) NOT NULL,
    USERNAME VARCHAR2(50)  NOT NULL,
    EMAIL    VARCHAR2(150) NOT NULL,
    ACTIVO   NUMBER(1)     DEFAULT 1 NOT NULL,
    ROL_ID   NUMBER,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIOS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIOS_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE INDEX APPUSER.IX_USUARIOS_ROL ON APPUSER.USUARIOS (ROL_ID);

CREATE TABLE APPUSER.AUDITORIA_EVENTOS (
    ID              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EVENTO_ID       VARCHAR2(64)  NOT NULL,
    TIPO_EVENTO     VARCHAR2(100) NOT NULL,
    ASUNTO          VARCHAR2(200) NOT NULL,
    DATOS           CLOB,
    FECHA_EVENTO    TIMESTAMP     NOT NULL,
    FECHA_REGISTRO  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AUDITORIA PRIMARY KEY (ID),
    CONSTRAINT UK_AUDITORIA_EVENTO UNIQUE (EVENTO_ID)
);

CREATE INDEX APPUSER.IX_AUDITORIA_TIPO ON APPUSER.AUDITORIA_EVENTOS (TIPO_EVENTO);

CREATE TABLE APPUSER.NOTIFICACIONES (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EVENTO_ID     VARCHAR2(64)   NOT NULL,
    TIPO          VARCHAR2(50)   NOT NULL,
    DESTINATARIO  VARCHAR2(150),
    ASUNTO        VARCHAR2(200)  NOT NULL,
    MENSAJE       VARCHAR2(1000) NOT NULL,
    FECHA         TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_NOTIFICACIONES PRIMARY KEY (ID),
    CONSTRAINT UK_NOTIFICACIONES_EVENTO UNIQUE (EVENTO_ID, TIPO)
);
